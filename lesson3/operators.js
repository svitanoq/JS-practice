
// ==========================================
// 1. NUMBERS — ЧИСЛА
// ==========================================

const price = 0.1;
const delivery = 0.2;

const total = price + delivery;

console.log(total);
// Результат: 0.30000000000000004
// JavaScript іноді неточно працює з десятковими дробами.

console.log(total.toFixed(2));
// Результат: "0.30"
// toFixed(2) залишає 2 знаки після коми.
// Важливо: результат буде рядком (string).


// ==========================================
// 2. MATH — МАТЕМАТИЧНІ МЕТОДИ
// ==========================================

console.log(Math.abs(-10));
// Результат: 10
// abs() повертає абсолютне значення числа.

console.log(Math.pow(2, 3));
// Результат: 8
// pow() підносить число до степеня: 2 * 2 * 2.

console.log(Math.sqrt(25));
// Результат: 5
// sqrt() обчислює квадратний корінь.

console.log(Math.random());
// Випадкове число від 0 (включно) до 1 (не включаючи 1).


// ==========================================
// 3. STRINGS — РЯДКИ
// ==========================================

const username = "Vitalii";

console.log(username.length);
// Результат: 7
// length показує кількість символів у рядку.

console.log(username[0]);
// Результат: "V"
// Індексація символів починається з нуля.

console.log(username[username.length - 1]);
// Результат: "i"
// Отримуємо останній символ рядка.

console.log(username.toUpperCase());
// Результат: "VITALII"
// Перетворюємо всі літери на великі.

console.log(username.toLowerCase());
// Результат: "vitalii"
// Перетворюємо всі літери на маленькі.

console.log(username.includes("tal"));
// Результат: true
// Перевіряємо, чи містить рядок вказаний текст.

console.log(username.slice(0, 3));
// Результат: "Vit"
// Беремо символи з індексу 0 до індексу 3.
// Кінцевий індекс не включається.

console.log("  QA  ".trim());
// Результат: "QA"
// trim() видаляє пробіли на початку та в кінці рядка.


// ==========================================
// 4. ARITHMETIC OPERATORS — АРИФМЕТИЧНІ ОПЕРАТОРИ
// ==========================================

console.log(10 + 5); // 15 — додавання
console.log(10 - 5); // 5  — віднімання
console.log(10 * 5); // 50 — множення
console.log(10 / 5); // 2  — ділення
console.log(10 % 3); // 1  — залишок від ділення


// ==========================================
// 5. INCREMENT AND DECREMENT
// ІНКРЕМЕНТ І ДЕКРЕМЕНТ
// ==========================================

let score = 10;

score++;
// Збільшуємо значення score на 1. Тепер 11.

score--;
// Зменшуємо значення score на 1. Тепер 10.

console.log(score); // 10


// ==========================================
// 6. COMPARISON OPERATORS — ОПЕРАТОРИ ПОРІВНЯННЯ
// ==========================================

console.log(10 > 5);   // true — більше
console.log(10 < 5);   // false — менше
console.log(10 >= 10); // true — більше або дорівнює
console.log(10 <= 5);  // false — менше або дорівнює

console.log(5 == "5");
// true — нестроге порівняння, типи можуть перетворюватися.

console.log(5 === "5");
// false — строге порівняння, число та рядок мають різні типи.

console.log(5 != "5");
// false — значення однакові після перетворення типів.

console.log(5 !== "5");
// true — типи даних відрізняються.


// ==========================================
// 7. LOGICAL OPERATORS — ЛОГІЧНІ ОПЕРАТОРИ
// ==========================================

const age = 26;
const hasTicket = true;

console.log(age >= 18 && hasTicket);
// true — обидві умови мають бути істинними.
// && означає AND (І).

console.log(age < 18 || hasTicket);
// true — достатньо однієї істинної умови.
// || означає OR (АБО).

console.log(!hasTicket);
// false — ! змінює true на false.
// ! означає NOT (НЕ).


// ==========================================
// 8. NULLISH COALESCING — ОПЕРАТОР ??
// ==========================================

const usernameFromAPI = null;

const name = usernameFromAPI ?? "Guest";

console.log(name);
// Результат: "Guest"
// Якщо значення null або undefined, використовуємо Guest.

console.log(0 ?? 100);
// Результат: 0
// Нуль не замінюється оператором ??


// ==========================================
// 9. TERNARY OPERATOR — ТЕРНАРНИЙ ОПЕРАТОР
// ==========================================

const balance = 50;

const status = balance > 0 ? "Active" : "Empty";

console.log(status);
// Результат: "Active"
// Умова ? значення_якщо_true : значення_якщо_false.


// ==========================================
// 10. OPERATOR PRECEDENCE — ПРІОРИТЕТ ОПЕРАТОРІВ
// ==========================================

console.log(2 + 3 * 4);
// Результат: 14
// Спочатку множення, потім додавання.

console.log((2 + 3) * 4);
// Результат: 20
// Дужки змушують спочатку виконати додавання.


// ==========================================
// 11. TYPEOF — ПЕРЕВІРКА ТИПУ ДАНИХ
// ==========================================

console.log(typeof 100);       // number — число
console.log(typeof "100");     // string — рядок
console.log(typeof true);      // boolean — логічний тип
console.log(typeof undefined); // undefined — значення не визначене


// ==========================================
// 12. TYPE CONVERSION — ПЕРЕТВОРЕННЯ ТИПІВ
// ==========================================

console.log(Number("25"));
// 25 — перетворюємо рядок на число.

console.log(String(25));
// "25" — перетворюємо число на рядок.

console.log(Boolean(0));
// false — нуль перетворюється на false.

console.log(Boolean("QA"));
// true — непорожній рядок перетворюється на true.


// ==========================================
// 13. PARSEINT AND PARSEFLOAT
// ==========================================

console.log(parseInt("19.85"));
// 19 — отримуємо ціле число.

console.log(parseFloat("19.85"));
// 19.85 — зберігаємо дробову частину.


// ==========================================
// 14. IMPLICIT TYPE CONVERSION
// НЕЯВНЕ ПЕРЕТВОРЕННЯ ТИПІВ
// ==========================================

console.log("7" + 3);
// "73" — рядок і число об'єднуються в рядок.

console.log("7" - 3);
// 4 — JavaScript перетворює рядок на число.


// ==========================================
// 15. UNARY PLUS AND DOUBLE NOT
// УНАРНИЙ ПЛЮС І ПОДВІЙНЕ ЗАПЕРЕЧЕННЯ
// ==========================================

console.log(+"30");
// 30 — унарний плюс перетворює рядок на число.

console.log(!!1);
// true — подвійне заперечення перетворює значення на Boolean.

console.log(!!0);
// false — нуль є хибним значенням (falsy).
